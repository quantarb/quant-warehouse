_TEMPORAL_NAME = re.compile(
    r"(^|_)(date|datetime|timestamp|time|updated|created|published|publication|fetched|"
    r"accepted|disclosed|disclosure|available|availability|effective|recorded|expiry|"
    r"expiration|maturity)(_|$)|(_at$)"
)
_IDENTITY_NAME = re.compile(
    r"(^|_)(id|key|index|uuid|identifier|symbol|ticker|cik|cusip|isin|lei)(_|$)"
)


def retained_schema_reason(name: str, dtype: pl.DataType) -> str | None:
    """Protect actual identity and timing; names/categories alone are payloads."""
    normalized = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()
    if _TEMPORAL_NAME.search(normalized):
        return "temporal or availability name"
    if _IDENTITY_NAME.search(normalized):
        return "record identity or key name"
    if dtype.is_temporal():
        return "temporal dtype"
    if isinstance(dtype, (pl.List, pl.Array, pl.Struct)):
        return "nested schema requires explicit review"
    return None
